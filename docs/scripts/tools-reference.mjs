// Writes the tools reference (content/reference/tools.md, and its Spanish page) from the built server's
// own tools/list, so it can't drift from the code. Needs `npm run build` at the root first.
//   node scripts/tools-reference.mjs
// The English page has the titles and descriptions the agent reads; the Spanish page, their translations in
// scripts/tools.es.json, each kept with the English it translates: when a tool's text changes and its
// translation doesn't, this fails and says which, so the Spanish page never describes an older tool.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { Client } from "../../node_modules/@modelcontextprotocol/sdk/dist/esm/client/index.js";
import { StdioClientTransport } from "../../node_modules/@modelcontextprotocol/sdk/dist/esm/client/stdio.js";

const SERVER = fileURLToPath(new URL("../../dist/server.mjs", import.meta.url));
const OUT = {
  en: fileURLToPath(new URL("../content/reference/tools.md", import.meta.url)),
  es: fileURLToPath(new URL("../i18n/es/docusaurus-plugin-content-docs/current/reference/tools.md", import.meta.url)),
};
const TEXT = {
  en: {
    title: "Tools",
    intro: (n) => `This server has **${n} tools**. This page is generated from the server itself, so it lists them exactly as your AI app gets them, with the descriptions the agent reads. You don't call tools yourself: you ask in your own words, and the agent picks them.`,
    head: ["Tool", "What it does", "Only reads"],
    inputs: "Inputs",
    params: ["Input", "Required", "Type", "Description"],
    none: "No inputs.",
  },
  es: {
    title: "Herramientas",
    intro: (n) => `Este servidor tiene **${n} herramientas**. Esta página se genera a partir del propio servidor, así que las muestra tal como las recibe tu aplicación de IA, con las descripciones que lee el agente (él las lee en inglés; aquí van traducidas). Tú no llamas a las herramientas: pides lo que necesitas con tus palabras, y el agente las elige.`,
    head: ["Herramienta", "Qué hace", "Solo lee"],
    inputs: "Entradas",
    params: ["Entrada", "Obligatoria", "Tipo", "Descripción"],
    none: "Sin entradas.",
  },
};

const client = new Client({ name: "tools-reference", version: "0.0.0" });
await client.connect(new StdioClientTransport({ command: process.execPath, args: [SERVER], stderr: "ignore" }));
const { tools } = await client.listTools();
await client.close();

const SPANISH = JSON.parse(readFileSync(new URL("./tools.es.json", import.meta.url), "utf8"));
const stale = [];
/** The Spanish for one of a tool's texts; the English, noting why, when its translation is missing or older. */
function spanish(where, pair, english) {
  if (!pair) stale.push(`${where}: no translation`);
  else if (pair[0] !== english) stale.push(`${where}: the English changed`);
  return pair && pair[0] === english ? pair[1] : english;
}
const TEXTS = {
  en: (tool) => ({ title: tool.title, description: tool.description, input: (name, schema) => schema.description }),
  es: (tool) => {
    const t = SPANISH[tool.name] ?? {};
    return {
      title: spanish(`${tool.name}.title`, t.title, tool.title),
      description: spanish(`${tool.name}.description`, t.description, tool.description),
      input: (name, schema) => (schema.description ? spanish(`${tool.name}.inputs.${name}`, t.inputs?.[name], schema.description) : ""),
    };
  },
};

const cell = (text) => String(text ?? "").replace(/\|/g, "\\|").replace(/\n+/g, " ").replace(/[{}<>]/g, (c) => `&#${c.charCodeAt(0)};`);
const typeOf = (schema) => (schema?.enum ? schema.enum.map((v) => `\`${v}\``).join(", ") : schema?.type === "array" ? `${schema.items?.type ?? "value"} list` : (schema?.type ?? ""));

for (const [lang, t] of Object.entries(TEXT)) {
  const lines = ["---", `title: ${t.title}`, `sidebar_label: ${t.title}`, "---", "", "<!-- Generated by docs/scripts/tools-reference.mjs from the server's tools/list: don't edit by hand. -->", "", `# ${t.title}`, "", t.intro(tools.length), ""];
  lines.push(`| ${t.head.join(" | ")} |`, "| --- | --- | :-: |");
  const texts = new Map(tools.map((tool) => [tool, TEXTS[lang](tool)]));
  for (const tool of tools) lines.push(`| [\`${tool.name}\`](#${tool.name.replace(/_/g, "-")}) | ${cell(texts.get(tool).title)} | ${tool.annotations?.readOnlyHint ? "✓" : ""} |`);
  for (const tool of tools) {
    const text = texts.get(tool);
    lines.push("", `## \`${tool.name}\` {#${tool.name.replace(/_/g, "-")}}`, "", `**${cell(text.title)}**`, "", cell(text.description), "");
    const properties = Object.entries(tool.inputSchema?.properties ?? {});
    if (!properties.length) {
      lines.push(`*${t.none}*`);
      continue;
    }
    const required = new Set(tool.inputSchema?.required ?? []);
    lines.push(`| ${t.params.join(" | ")} |`, "| --- | :-: | --- | --- |");
    for (const [name, schema] of properties) lines.push(`| \`${name}\` | ${required.has(name) ? "✅" : ""} | ${typeOf(schema)} | ${cell(text.input(name, schema))} |`);
  }
  mkdirSync(dirname(OUT[lang]), { recursive: true });
  writeFileSync(OUT[lang], `${lines.join("\n")}\n`);
}
if (stale.length) {
  console.error(`The Spanish tools reference needs its translations in docs/scripts/tools.es.json:\n${stale.map((s) => `- ${s}`).join("\n")}`);
  process.exit(1);
}
console.log(`tools reference: ${tools.length} tools, in English and Spanish.`);
